import { expect, test, type Page } from '@playwright/test'

const rows = (page: Page) => page.locator('.vxe-table--main-wrapper .vxe-body--row')

test('virtual rows, drag persistence, infinite batches and responsive layout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/table')
  await expect(page.getByTestId('record-count')).toHaveText('10.000 dòng')
  await expect(rows(page).first()).toBeVisible()
  expect(await rows(page).count()).toBeLessThan(100)
  const firstRow = rows(page).first()
  const handle = firstRow.locator('.vxe-cell--drag-handle')
  const target = rows(page).nth(3)
  const from = await handle.boundingBox()
  const to = await target.boundingBox()
  if (!from || !to) throw new Error('Row drag targets missing')
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(from.x + 10, to.y + to.height - 5, { steps: 15 })
  await page.waitForTimeout(200)
  await page.mouse.up()
  await expect(page.locator('.activity')).toContainText('Hàng SP-000001')
  await expect(rows(page).first()).toContainText('SP-000002')

  const headers = page.locator('.vxe-table--main-wrapper .vxe-header--column')
  const colFrom = await headers.nth(2).locator('.vxe-cell--drag-handle').boundingBox()
  const colTo = await headers.nth(4).boundingBox()
  if (!colFrom || !colTo) throw new Error('Column drag targets missing')
  await page.mouse.move(colFrom.x + colFrom.width / 2, colFrom.y + colFrom.height / 2)
  await page.mouse.down()
  await page.mouse.move(colTo.x + colTo.width - 10, colTo.y + colTo.height / 2, { steps: 15 })
  await page.waitForTimeout(200)
  await page.mouse.up()
  await expect(page.locator('.activity')).toContainText('Cột Mã sản phẩm')
  const reorderedHeaders = await headers.allTextContents()

  await page.getByRole('button', { name: 'Đến cuối bảng' }).click()
  await expect(page.getByTestId('record-count')).toHaveText('10.050 dòng')
  await expect(page.getByRole('status')).toContainText('1 lượt tải thêm')
  await page.getByRole('button', { name: 'Đến cuối bảng' }).click()
  await expect(page.getByTestId('record-count')).toHaveText('10.100 dòng')
  await page.getByRole('button', { name: 'Về đầu bảng' }).click()
  await expect(rows(page).first()).toContainText('SP-000002')
  expect(await headers.allTextContents()).toEqual(reorderedHeaders)
  expect(await rows(page).count()).toBeLessThan(100)
  await page.getByRole('checkbox').uncheck()
  await page.getByRole('button', { name: 'Đến cuối bảng' }).click()
  await page.waitForTimeout(700)
  await expect(page.getByTestId('record-count')).toHaveText('10.100 dòng')
  await page.getByRole('button', { name: 'Về đầu bảng' }).click()
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
