      await expect(reports).not.toBeVisible()
      await expect(page.getByRole('heading', { level: 1 })).toHaveText('A01.1 · Doanh thu theo cửa hàng')
      await capture(page, `../.impeccable/review/${repo}-mobile-content.png`)
      await reportTrigger.tap()
      await expect(reports.getByRole('heading')).toHaveText('A01 · Doanh thu bán hàng')
      await expect(reports.getByRole('link', { name: 'A01.1 Doanh thu theo cửa hàng', exact: true })).toHaveAttribute('aria-current', 'page')
      await reports.getByRole('button', { name: 'Quay lại cấp trước', exact: true }).tap()
      await expect(reports.getByRole('heading')).toHaveText('Báo cáo A')
      await reports.getByRole('button', { name: 'Đóng menu Báo cáo' }).tap()
