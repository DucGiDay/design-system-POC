import { expect, test, type Page } from '@playwright/test'

async function capture(page: Page, path: string) {
  // Await both drawer entry and any queued Vue leave/enter sequence before capture.
  await page.evaluate(async () => {
    for (let pass = 0; pass < 3; pass++) {
      const running = document.getAnimations().filter(animation => animation.playState === 'running' && animation.effect?.getTiming().iterations !== Infinity)
      await Promise.all(running.map(animation => animation.finished.catch(() => {})))
      await new Promise<void>(resolve => requestAnimationFrame(() => resolve()))
    }
  })
  const drawer = page.locator('.cms-menu-dialog[open]')
  if (await drawer.count()) await expect.poll(() => drawer.evaluate(element => element.getBoundingClientRect().left)).toBe(0)
  await page.screenshot({ path, fullPage: true, animations: 'disabled' })
}

