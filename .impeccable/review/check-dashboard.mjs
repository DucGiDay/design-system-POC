import { chromium } from '../../vxe-table-poc/node_modules/@playwright/test/index.mjs'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const out = new URL('./', import.meta.url)
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://127.0.0.1:5174/')
await page.locator('.cms-dashboard__report-bottom').last().waitFor()
await page.evaluate(() => document.fonts.ready)
assert.equal(await page.locator('.cms-report-card').count(), 9)
assert.equal(await page.locator('.cms-card-metric').count(), 4)
await page.screenshot({ path: new URL('desktop.png', out).pathname.replace(/^\/(\w:)/, '$1') })
const diagnostics = []
for (const [width, height, name] of [[1440, 1000, 'desktop'], [1280, 720, 'user-1280'], [390, 844, 'mobile']]) {
  await page.setViewportSize({ width, height })
  const scroller = page.locator(width < 960 ? '.cms-content' : '.cms-dashboard__scroll')
  await scroller.evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: new URL(`${name}.png`, out).pathname.replace(/^\/(\w:)/, '$1') })
  diagnostics.push(await page.evaluate(() => ({ width: innerWidth, documentWidth: document.documentElement.scrollWidth, contentWidth: document.querySelector('.cms-content').clientWidth, scrollWidth: document.querySelector('.cms-content').scrollWidth, brokenImages: [...document.querySelectorAll('.cms-dashboard img')].filter(img => !img.complete || !img.naturalWidth).map(img => img.src), missingIcons: [...document.querySelectorAll('.cms-dashboard .app-icon')].filter(el => getComputedStyle(el).maskImage === 'none').length })))
  const topFilter = await page.locator('.cms-dashboard__filters').boundingBox()
  await scroller.evaluate(el => { el.scrollTop = el.scrollHeight })
  const bottomFilter = await page.locator('.cms-dashboard__filters').boundingBox()
  if (width < 960) assert.ok(bottomFilter.y < topFilter.y - 100)
  else assert.equal(bottomFilter.y, topFilter.y)
  await page.screenshot({ path: new URL(`${name}-bottom.png`, out).pathname.replace(/^\/(\w:)/, '$1') })
}
await page.setViewportSize({ width: 1440, height: 1000 })
await page.locator('.cms-dashboard__scroll').evaluate(el => { el.scrollTop = 0 })
await page.getByRole('button', { name: 'GROSS', exact: true }).click()
assert.match(await page.locator('.cms-dashboard__revenue').innerText(), /660.400/)
await page.getByRole('button', { name: 'NET', exact: true }).click()
await page.getByRole('button', { name: '7 ngày', exact: true }).click()
assert.match(await page.locator('.cms-dashboard__hero-label').innerText(), /7 NGÀY/)
await page.getByRole('button', { name: 'Hôm nay', exact: true }).click()
const filterBefore = await page.locator('.cms-dashboard__filters').boundingBox()
await page.locator('.cms-dashboard__scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
const filterAfter = await page.locator('.cms-dashboard__filters').boundingBox()
assert.equal(filterBefore.y, filterAfter.y)
assert.ok(await page.locator('.cms-dashboard__scroll').evaluate(el => el.scrollTop > 0))
await page.locator('.cms-dashboard__scroll').evaluate(el => { el.scrollTop = 0 })
await page.getByRole('button', { name: 'Số lượng', exact: true }).click()
assert.match(await page.locator('.cms-dashboard__products li').first().innerText(), /Trân châu/)
await page.getByRole('button', { name: 'Doanh thu (net)', exact: true }).click()
await page.locator('.cms-dashboard__scope summary').click()
await page.locator('.cms-dashboard__scope-popover input').first().uncheck()
await page.getByLabel('Cầu Giấy', { exact: true }).check()
await page.locator('.cms-dashboard__scope-popover').getByRole('button', { name: 'Áp dụng' }).click()
assert.match(await page.locator('.cms-dashboard__revenue').innerText(), /51.033/)
await page.locator('.cms-dashboard__scope summary').click()
await page.locator('.cms-dashboard__scope-popover input').first().check()
await page.locator('.cms-dashboard__scope-popover').getByRole('button', { name: 'Áp dụng' }).click()
await page.locator('.cms-dashboard__dates summary').click()
await page.getByLabel('Từ ngày').fill('2026-10-20')
await page.locator('.cms-dashboard__date-popover').getByRole('button', { name: 'Áp dụng' }).click()
assert.equal(await page.locator('[aria-invalid=true]').count(), 1)
await page.getByLabel('Từ ngày').fill('2026-10-13')
await page.locator('.cms-dashboard__date-popover').getByRole('button', { name: 'Áp dụng' }).click()
await page.getByRole('button', { name: 'Hôm nay', exact: true }).click()
await page.getByRole('button', { name: 'Xem chi tiết Top 5 mặt hàng', exact: true }).click()
assert.equal(await page.locator('dialog[open] tbody tr').count(), 5)
await page.screenshot({ path: new URL('detail.png', out).pathname.replace(/^\/(\w:)/, '$1') })
await page.keyboard.press('Escape')
for (const format of ['CSV', 'SVG', 'PNG']) {
  await page.locator('.cms-report-card').first().locator('summary').click()
  const promise = page.waitForEvent('download')
  await page.getByRole('button', { name: `Tải ${format}`, exact: true }).click()
  const download = await promise
  assert.equal(await download.failure(), null)
}
await page.locator('.cms-dashboard__quick input').fill('khuyến mại')
await page.locator('.cms-dashboard__search-results button').click()
assert.equal(await page.locator('dialog[open] tbody tr').count(), 5)
await page.keyboard.press('Escape')
await page.getByRole('switch', { name: 'Chế độ tối' }).click()
await page.screenshot({ path: new URL('dark.png', out).pathname.replace(/^\/(\w:)/, '$1') })
await page.getByRole('switch', { name: 'Chế độ tối' }).click()
await page.locator('.cms-dashboard__actions').getByRole('button', { name: 'VI', exact: true }).click()
await page.screenshot({ path: new URL('english.png', out).pathname.replace(/^\/(\w:)/, '$1') })
await page.locator('.cms-dashboard__actions').getByRole('button', { name: 'EN', exact: true }).click()
for (const diagnostic of diagnostics) { assert.equal(diagnostic.documentWidth, diagnostic.width); assert.ok(diagnostic.scrollWidth <= diagnostic.contentWidth + 1); assert.equal(diagnostic.brokenImages.length, 0); assert.equal(diagnostic.missingIcons, 0) }
assert.deepEqual(errors, [])
await writeFile(new URL('dashboard-checks.json', out), JSON.stringify({ diagnostics, errors, interactions: ['net/gross', 'period', 'ranking sort', 'store scope', 'date validation', 'details', 'csv/svg/png export', 'quick search', 'dark mode', 'English'] }, null, 2))
console.log(JSON.stringify({ diagnostics, errors, result: 'pass' }))
await browser.close()

